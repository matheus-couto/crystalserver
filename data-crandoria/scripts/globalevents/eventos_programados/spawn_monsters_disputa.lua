local function shuffle(list)
	for i = #list, 2, -1 do
		local j = math.random(i)
		list[i], list[j] = list[j], list[i]
	end
	return list
end

-- Tiles validos e vagos da area, em ordem aleatoria
local function getFreeTiles(area)
	local from, to = area.fromPosition, area.toPosition
	local tiles = {}
	for x = from.x, to.x do
		for y = from.y, to.y do
			local pos = Position(x, y, from.z)
			local tile = Tile(pos)
			if tile
				and tile:getCreatureCount() == 0
				and not tile:hasFlag(TILESTATE_BLOCKSOLID)
				and not tile:hasFlag(TILESTATE_PROTECTIONZONE)
				and not tile:hasFlag(TILESTATE_FLOORCHANGE) then
				tiles[#tiles + 1] = pos
			end
		end
	end
	return shuffle(tiles)
end

local function spawnConfig(config)
	local pools = {} -- uma lista de tiles por area, compartilhada entre as entradas dela

	for _, entry in ipairs(config) do
		local pool = pools[entry.area]
		if not pool then
			pool = getFreeTiles(entry.area)
			pools[entry.area] = pool
		end

		local created = 0
		while created < entry.count and #pool > 0 do
			local pos = table.remove(pool)
			if Game.createMonster(entry.name, pos, false, false) then
				created = created + 1
			end
		end

		if created < entry.count then
			print(string.format("[Disputa de Poder] %s: criados %d de %d (faltaram tiles livres)", entry.name, created, entry.count))
		end
	end
end

local monstersDisputa = GlobalEvent("monstersDisputa")

function monstersDisputa.onTime(interval)

	local day = os.date("%A")

	if day ~= "Sunday" then
		return true
	end

	local index = math.random(#configs)
	print("[Disputa de Poder] config de monstros sorteada: " .. index)
	spawnConfig(configs[index])

	return true
end

