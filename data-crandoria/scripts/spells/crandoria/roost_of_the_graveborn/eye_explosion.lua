local spell = Spell("instant")

function spell.onCastSpell(creature, var)
	local storage = creature:getStorageValue("eyeExplosion")
	local timeNow = os.time()
	if storage < 1 then
		creature:setStorageValue("eyeExplosion", timeNow + 6)
		return true
	else
		if storage > timeNow() then
			return true
		else
			creature:remove()
			return combat:execute(creature, var)
		end
	end
	return true
end

