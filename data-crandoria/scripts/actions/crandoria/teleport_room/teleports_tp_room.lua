local teleport = MoveEvent()

function teleport.onStepIn(creature, item, position, fromPosition)
    local player = creature:getPlayer()
    if not player then return true end

    local teleportData = nil
    for pos, data in pairs(teleports) do
        if pos == position then -- Aqui comparamos os objetos Position
            teleportData = data
            break
        end
    end

    if not teleportData then 
        player:sendTextMessage(MESSAGE_STATUS_WARNING, "NOPE")
        return true 
    end

    local posX = item:getPosition().x
    local poxY = item:getPosition().y

    local valor = 250
    if posX > 4924 and posX < 4938 then
        valor = 25000
    elseif posX > 4938 and posX < 4951 then
        valor = 15000
    elseif posX > 4951 and posX < 4972 then
        valor = 5000
    end

    if item.itemid == 22761 then
        if player:getItemCount(22720) < 1 then
            player:sendTextMessage(MESSAGE_EVENT_ADVANCE, "Voce precisa de 1 Arena Token para acessar um teleport de Boss.")
            player:teleportTo(fromPosition)
            return true
        else
            player:teleportTo(teleportData.destination)
            player:removeItem(22720, 1)
        end
    elseif item.itemid == 1959 then
        if player:getVipDays() > 0 then
            player:teleportTo(teleportData.destination)
            return true
        else
            if player:getLevel() <= 25 then
                player:teleportTo(teleportData.destination)
                return true
            else
                if player:getStorageValue(Storage.Quest.Crandoria.NilluxQuest.TimerEffect) < os.time() then
                    if player:removeMoneyBank(valor) then
                        player:teleportTo(teleportData.destination)
                        return true
                    else
                        player:sendTextMessage(MESSAGE_EVENT_ADVANCE, "Voce precisa de "..valor.." gold coins no banco para acessar esse teleport.")
                        player:teleportTo(fromPosition)
                        return true
                    end
                else
                    player:teleportTo(teleportData.destination)
                    return true
                end
            end
        end
    end
    return true
end

