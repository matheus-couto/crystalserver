local teleport = MoveEvent()

function teleport.onStepIn(creature, item, position, fromPosition)
    local player = creature:getPlayer()
    if not player then return true end

    local teleportData = nil
    for pos, data in pairs(teleports) do
        if pos == position then -- Aqui comparamos os objetos Position
            teleportData = data
            break
        end
    end

    if not teleportData then 
        player:sendTextMessage(MESSAGE_STATUS_WARNING, "NOPE")
        return true 
    end

    local valorOnline = teleportData.count
    if player:getVipDays() > 0 then
        valorOnline = teleportData.countVIP
    end

    local timeNow = os.time()
    local passe = player:getStorageValue(Storage.Quest.Crandoria.TeleportRoom.Passe)


    if item.itemid == 1959 then
        if player:getLevel() <= 25 then
            player:teleportTo(teleportData.destination)
            player:sendTextMessage(MESSAGE_EVENT_ADVANCE, "Teleport liberado por possuir nivel 25 ou inferior.")
            return true
        else
            if passe > timeNow then
                player:teleportTo(teleportData.destination)
                return true
            else
                if player:getItemCount(22723) < valorOnline then
                    player:sendTextMessage(MESSAGE_EVENT_ADVANCE, "Voce precisa de "..valorOnline.." Online Token(s) para acessar esse teleport.")
                    player:teleportTo(fromPosition)
                    return true
                else
                    player:teleportTo(teleportData.destination)
                    return true
                end
            end
        end
    end
    return true
end

