local teleport = MoveEvent()

function teleport.onStepIn(creature, item, position, fromPosition)
    local player = creature:getPlayer()
    if not player then return true end

    local teleportData = nil
    for pos, data in pairs(teleportsBoss) do
        if pos == position then -- Aqui comparamos os objetos Position
            teleportData = data
            break
        end
    end

    if not teleportData then 
        player:sendTextMessage(MESSAGE_STATUS_WARNING, "NOPE")
        return true 
    end

    local valorGold = 3
    if player:getVipDays() > 0 then
        valorGold = 1
    end

    local timeNow = os.time()
    local storage = player:getStorageValue(teleportData.storage)
    local passe = player:getStorageValue(Storage.Quest.Crandoria.TeleportRoom.Passe)

    local function getBossTimer(player, data)
        if data.boss then
            return player:getBossCooldown(data.boss) or 0
        end
        if data.storage then
            return player:getStorageValue(data.storage)
        end
        print("[BossTeleport] entrada sem 'boss' nem 'storage' valido, destino:", data.destination)
        return -1
    end

    if item.itemid == 22761 then
        if storage < 1 then
            player:sendTextMessage(MESSAGE_EVENT_ADVANCE, "Voce precisa enfrentar esse boss pelo menos uma vez para acessar o seu teleport.")
            player:teleportTo(fromPosition)
            return true
        else
            if storage > timeNow then
                player:sendTextMessage(MESSAGE_EVENT_ADVANCE, "Voce ainda precisa aguardar para enfrentar esse boss novamente.")
                player:teleportTo(fromPosition)
                return true
            else
                if passe > timeNow then
                    player:teleportTo(teleportData.destination)
                    return true
                else
                    if player:getItemCount(22721) < valorGold then
                        player:sendTextMessage(MESSAGE_EVENT_ADVANCE, "Voce precisa de "..valorGold.." Gold Token(s) para acessar um teleport de Boss.")
                        player:teleportTo(fromPosition)
                        return true
                    else
                        player:teleportTo(teleportData.destination)
                        player:removeItem(22721, valorGold)
                    end
                end
            end
        end
    end
    return true
end

